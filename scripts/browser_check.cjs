const {chromium} = require('../build/browser/node_modules/playwright');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:960}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:39200');
  await page.waitForFunction(()=>document.querySelector('#model-select').options.length>0);
  await page.getByRole('button',{name:'＋ 新对话',exact:true}).click();
  await page.waitForTimeout(400);
  await page.locator('#file-input').setInputFiles({name:'test.txt',mimeType:'text/plain',buffer:Buffer.from('Test attachment: the project name is Cedar.')});
  await page.waitForFunction(()=>document.querySelector('#pending').textContent.includes('已就绪'));
  await page.locator('#example-code').click();
  await page.locator('#run').click();
  await page.waitForFunction(()=>document.querySelector('#run-state').textContent.includes('退出码 0'));
  if(!await page.locator('#generated').textContent().then(t=>t.includes('result.txt')))throw new Error('Missing output file');
  await page.screenshot({path:'build/workspace-desktop.png',fullPage:true});
  await page.locator('#model-center').click();
  await page.waitForSelector('.model-card');
  await page.screenshot({path:'build/model-center.png'});
  await page.locator('#close-models').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('#toggle-python').click();
  await page.screenshot({path:'build/workspace-mobile.png'});
  const text=await page.locator('body').textContent();
  if(text.includes('计划模式')||text.includes('目标模式'))throw new Error('Legacy modes visible');
  if(errors.length)throw new Error(errors.join('\n'));
  console.log(JSON.stringify({passed:true,checks:['desktop layout','attachment upload preview','manual Python run','generated file in conversation','model center','mobile layout','no legacy mode buttons'],errors},null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
